#!/usr/bin/env node
/**
 * Walks `Common/res/def/**\/*.def` and emits
 * `src/builtin-defines-data.ts` — a single TypeScript module that
 * exports the concatenated Ludii built-in macro library as a string.
 *
 * Run via `npm run gen:builtin-defines`. Re-run when the upstream .def
 * library changes.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const enginePkg = resolve(here, "..");
const repoRoot = resolve(enginePkg, "../../..");
const defRoot = join(repoRoot, "Common", "res", "def");
const outputFile = join(enginePkg, "src", "builtin-defines-data.ts");

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    let s;
    try {
      s = statSync(full);
    } catch {
      continue;
    }
    if (s.isDirectory()) walk(full, out);
    else if (entry.endsWith(".def")) out.push(full);
  }
  return out;
}

const files = walk(defRoot).sort();
const chunks = [];
for (const file of files) {
  const rel = relative(repoRoot, file);
  const text = readFileSync(file, "utf8");
  chunks.push(`// ${rel}\n${text}`.trimEnd());
}

const concatenated = chunks.join("\n\n");
// Escape for a JS template literal: backslashes, backticks, ${…}.
const escaped = concatenated
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\${/g, "\\${");

const banner = `/* AUTO-GENERATED by scripts/build-builtin-defines.mjs — do not edit by hand. */`;
const body = `${banner}\n\n/**\n * Concatenated source of every \`Common/res/def/**.def\` file.\n * ${files.length} built-in defines, ${concatenated.length} bytes.\n */\nexport const BUILTIN_DEFINES_LUD = \`${escaped}\`;\n`;

writeFileSync(outputFile, body);
console.log(
  `Wrote ${relative(enginePkg, outputFile)} (${files.length} defines, ${concatenated.length} bytes).`,
);
