#!/usr/bin/env node
// Regenerates src/ludemes/index.ts — a barrel that side-effect-imports every
// transliterated ludeme file so their register() calls run. Agents only ADD
// ludeme files (zero shared-file edits); this script (run by the coordinator,
// not the agents) regenerates the barrel from the filesystem, so there is never
// a merge conflict on the barrel itself.
import fs from 'node:fs';
import path from 'node:path';

const ENGINE = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const LUDEMES = path.join(ENGINE, 'src', 'ludemes');
const BARREL = path.join(LUDEMES, 'index.ts');
const SKIP = new Set(['index.ts', 'registry.ts']);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (p.endsWith('.ts') && !SKIP.has(e.name)) out.push(p);
  }
  return out;
}

const files = walk(LUDEMES).sort();
const imports = files
  .map((f) => './' + path.relative(LUDEMES, f).replace(/\.ts$/, '.js'))
  .map((rel) => `import '${rel}';`)
  .join('\n');

const header = `// AUTO-GENERATED by tools/gen-ludeme-barrel.mjs — do not edit by hand.
// Side-effect imports of every transliterated ludeme file so their register()
// calls run. compile.ts imports this barrel once (at the bottom of the module).
`;
fs.writeFileSync(BARREL, header + imports + '\n');
console.log(`Regenerated ${path.relative(ENGINE, BARREL)} with ${files.length} ludeme imports.`);
